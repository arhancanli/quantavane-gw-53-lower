#!/usr/bin/env python3
"""Write Gw53/Colourings.lean: good exact colourings for the rows GW(r; 5, 3) and GW(r; 6, 3).

Row (5, 3) (no rainbow 5-term AP, no monochromatic 3-term AP): the good exact r-colourings of [1, n]
for r = 5, ..., 17 of Quantavane's paper "Power-residue colourings and exact Gallai-van der Waerden
numbers" (Section 5.5 and Appendix B), read from the file gw/k5/witnesses_k5l3.txt of the public data
repository arhancanli/quantavane-gw-data. Lengths n = 85, 85, 80, 80, 78, 78, 78, 77, 73, 73, 59, 59, 52.

Row (6, 3) (no rainbow 6-term AP, no monochromatic 3-term AP), by the paper's Lemma 2.3 (end
extension) applied to the colourings of [1, 85]: shift by one and give the new point 1 a new colour
(r = 6 on [1, 86], from the 5-colouring), or give the new points 1 and 87 two different new colours
(r = 7 and r = 8 on [1, 87], from the 5- and the 6-colouring; 5 does not divide 86, so no rainbow
6-term AP runs from one new point to the other).

The script checks every colouring by brute force (every colour occurs; no rainbow k-term and no
monochromatic 3-term AP) and writes each as a natural number in base 32 (point x gets the digit x - 1).
Nothing here is trusted by the Lean proof: Lean's kernel checks the colourings it is given.

Usage: make_colourings.py witnesses_k5l3.txt OUT.lean
"""
import sys

DIG = '0123456789abcdefg'


def bad(c, k, l):
    n, out = len(c), 0
    for d in range(1, n):
        for x in range(1, n + 1):
            if x + (k - 1) * d <= n and len({c[x + i * d - 1] for i in range(k)}) == k:
                out += 1
            if x + (l - 1) * d <= n and len({c[x + i * d - 1] for i in range(l)}) == 1:
                out += 1
    return out


MAXW = 3000   # progressions (start points) per kernel check


def chunks(n, m, D, maxw):
    """Split the differences 1..D into consecutive pieces (lo, count) of at most maxw start points."""
    out, lo = [], 1
    while lo <= D:
        c = w = 0
        while lo + c <= D and (c == 0 or w + n - (m - 1) * (lo + c) <= maxw):
            w += n - (m - 1) * (lo + c)
            c += 1
        out.append((lo, c))
        lo += c
    return out


def main():
    wit, out = sys.argv[1], sys.argv[2]
    row5 = {}
    for line in open(wit):
        t = line.split()
        if not t or t[0].startswith('#'):
            continue
        r, n, s = int(t[0]), int(t[1]), t[2]
        if r >= 5:
            c = [DIG.index(ch) for ch in s]
            assert len(c) == n and sorted(set(c)) == list(range(r)), r
            assert bad(c, 5, 3) == 0, r
            row5[r] = c
    assert sorted(row5) == list(range(5, 18))
    lens = [len(row5[r]) for r in range(5, 18)]
    assert lens == [85, 85, 80, 80, 78, 78, 78, 77, 73, 73, 59, 59, 52], lens
    row6 = {6: [5] + row5[5], 7: [5] + row5[5] + [6], 8: [6] + row5[6] + [7]}
    for r, c in row6.items():
        assert sorted(set(c)) == list(range(r)) and bad(c, 6, 3) == 0, r
    with open(out, 'w') as f:
        f.write('module\n\npublic import Gw53.Check\n\n@[expose] public section\n\n')
        f.write('/-!\n# Good exact colourings for the rows `(5, 3)` and `(6, 3)` (generated by `scripts/make_colourings.py`)\n\n')
        f.write('Point `x` gets the base-32 digit `x - 1` of the constant (`digitCol`). Point 1 first, colours\n')
        f.write('`10, 11, …` written `a, b, …`:\n\n')
        for r in range(5, 18):
            f.write(f'* `(5, 3)`, `r = {r}`, `[1, {len(row5[r])}]`: `{"".join(DIG[v] for v in row5[r])}`\n')
        for r in (6, 7, 8):
            f.write(f'* `(6, 3)`, `r = {r}`, `[1, {len(row6[r])}]`: `{"".join(DIG[v] for v in row6[r])}`\n')
        f.write('\nThe colourings of the row `(5, 3)` are those of `gw/k5/witnesses_k5l3.txt` in the public data\n')
        f.write('repository; those of the row `(6, 3)` add one or two new colours at the ends of the colourings of\n')
        f.write('`[1, 85]`. Each is checked by `decide +kernel` (no `native_decide`): `allCols` (every colour\n')
        f.write('occurs) and `rangeTest` (every progression), which `good_of_tests` puts together.\n-/\n\n')
        f.write('namespace Gw53\n\n')
        for key, rows, k in (('a', row5, 5), ('b', row6, 6)):
            for r, c in sorted(rows.items()):
                n, m = len(c), 3
                D = n // (m - 1)
                assert (m - 1) * (D + 1) > n
                B = sum(v << (5 * i) for i, v in enumerate(c))
                assert all(((B >> (5 * (x - 1))) % 32) % r == c[x - 1] for x in range(1, n + 1))
                nm = f'{key}{r}'
                f.write(f'/-- The {r}-colouring of `[1, {n}]` for `(k, l) = ({k}, 3)` in base 32 (point `x` is digit `x - 1`). -/\n')
                f.write(f'def B{nm} : ℕ :=\n  {hex(B)}\n\n')
                f.write(f'/-- The good exact {r}-colouring of `[1, {n}]` for `(k, l) = ({k}, 3)`. -/\n')
                f.write(f'def col{nm} : ℕ → Fin {r} := digitCol {r} (by decide) B{nm}\n\n')
                f.write(f'theorem cols{nm} : allCols {r} B{nm} {n} {r} = true := by decide +kernel\n\n')
                pieces = chunks(n, m, D, MAXW)
                for j, (lo, cnt) in enumerate(pieces):
                    f.write(f'theorem rows{nm}_{j} : rangeTest {r} B{nm} {k} 3 {n} 3 {lo} {cnt} = true := by decide +kernel\n\n')
                f.write(f'theorem good{nm} : IsGoodExactColouring {r} {k} 3 {n} col{nm} :=\n')
                f.write(f'  good_of_tests (m := 3) (D := {D}) (by decide) (by decide) (by decide) (by decide) (by decide) cols{nm} (by\n')
                f.write('    intro d h1 h2\n')
                for j, (lo, cnt) in enumerate(pieces):
                    if j < len(pieces) - 1:
                        f.write(f'    by_cases c{j} : d < {lo + cnt}\n')
                        f.write(f'    · exact rangeTest_spec _ rows{nm}_{j} d (by omega) (by omega)\n')
                    else:
                        f.write(f'    exact rangeTest_spec _ rows{nm}_{j} d (by omega) (by omega))\n\n')
        f.write('end Gw53\n')
    print('wrote', out)


if __name__ == '__main__':
    main()
